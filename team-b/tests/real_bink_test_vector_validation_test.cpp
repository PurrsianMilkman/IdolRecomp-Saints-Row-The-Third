std::vector<uint8_t> readFile(const std::string& path) {
    std::ifstream f(path, std::ios::binary | std::ios::ate);
    if (!f) return {};
    std::streamsize n = f.tellg();
    if (n <= 0) return {};
    f.seekg(0);
    std::vector<uint8_t> buf(static_cast<size_t>(n));
    f.read(reinterpret_cast<char*>(buf.data()), n);
    if (!f) return {};
    return buf;
}

// Loads one fixture and verifies it against its designated (size, sha256)
// pin. Returns {} and prints why on any mismatch - the caller treats that
// as "fixture unusable", same as a missing file.
std::vector<uint8_t> loadVerified(const std::string& path, size_t expectedSize, const std::string& expectedSha,
                                   const std::string& label, bool& ok) {
    std::vector<uint8_t> data = readFile(path);
    if (data.empty()) {
        std::cout << "  MISSING: " << label << " ('" << path << "')\n";
        ok = false;
        return {};
    }
    const std::string actualSha = bink_test_sha256::computeSha256Hex(data.data(), data.size());
    if (data.size() != expectedSize || actualSha != expectedSha) {
        std::cout << "  HASH MISMATCH: " << label << " (expected " << expectedSize << " bytes / sha256 "
                  << expectedSha << ", got " << data.size() << " bytes / sha256 " << actualSha << ")\n";
        ok = false;
        return {};
    }
    std::cout << "  OK: " << label << " (" << data.size() << " bytes, sha256 " << actualSha << ")\n";
    return data;
}

// First 2 bytes of a dc_ac_coeffs_*.bin vector, little-endian signed 16-bit -
// the "DC literal"/"DC residual" value spec-bink-video-test-vectors.md's own
// CSV index names for each file. Used only to cross-check this test's own
// hardcoded expectation against the real bytes, independent of the CSV text.
int16_t firstDcWord(const std::vector<uint8_t>& v) {
    if (v.size() < 2) return 0;
    return static_cast<int16_t>(static_cast<uint16_t>(v[0]) | (static_cast<uint16_t>(v[1]) << 8));
}

