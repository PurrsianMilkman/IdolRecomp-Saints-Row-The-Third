int main() {
    using namespace sr3vehicle;

    vpp::ByteView real(kRealCvtfBytes, sizeof(kRealCvtfBytes));
    CHECK(sizeof(kRealCvtfBytes) == 16089);

    // --- Header: the 48-byte layout, corrected 2026-10-03. Every value
    // here was read directly off a hex dump of the real file, independent
    // of this reader's own implementation. ---
    {
        CvtfCatalog cat;
        std::string why;
        bool ok = CvtfCatalog::tryParse(real, cat, why);
        CHECK(ok);
        if (!ok) std::cerr << "tryParse failed: " << why << "\n";

        CHECK(cat.sectionCount() == 2);
        CHECK(cat.region1Count() == 28);            // +0x08, real bytes: 1c 00 00 00
        CHECK(cat.region1OffsetRaw() == 40);         // +0x0C, real bytes: 28 00 00 00 - this project's reader
                                                      // used to call this "entryCount2" and treat it as a count;
                                                      // it is the Region-1 table's own OFFSET (resolves via +8
                                                      // to 48, exactly where the 28 real quads start)
        CHECK(!cat.table2Offset().has_value());      // +0x10 real bytes: ff ff ff ff (sentinel - absent)
        CHECK(cat.table2Count() == 0);                // +0x14 real bytes: 00 00 00 00
        CHECK(cat.table3Offset().has_value());
        if (cat.table3Offset()) CHECK(*cat.table3Offset() == 9756);  // +0x18 raw 9748, +8 = 9756
        CHECK(cat.table3Count() == 5);                // +0x1C - matches Region 3's own already-documented
                                                        // "5 complete style presets" exactly

        // --- Region 1: 28 real entries, no more "2 leading header-like
        // quads" (that was an artifact of the OLD, wrong 16-byte header
        // computation coincidentally landing on the right byte offset in
        // this one sample - CORRECTED 2026-10-03). ---
        CHECK(cat.region1().size() == 28);
        if (cat.region1().size() == 28) {
            const CvtfRegion1Entry& e0 = cat.region1()[0];
            CHECK(e0.a == 488);
            CHECK(e0.b == 496);
            CHECK(e0.c == 508);
            CHECK(e0.tag == 0x101);
            CHECK(e0.optionCount == 1);
            CHECK(e0.tagUpperBits == 1);
            CHECK(!e0.aIsSentinel);
            CHECK(!e0.bIsSentinel);
            CHECK(!e0.cIsSentinel);
            CHECK(e0.name == "Chassis");      // a+8 = 496, real bytes: "Chassis\0"
            CHECK(e0.variant == "Standard");  // b+8 = 504, real bytes: "Standard\0"
            CHECK(e0.options.size() == 1);
        }

        // --- Region 2 (wheel names): a real dword-offset array (+0x20/
        // +0x24), NOT a content-shape scan - CORRECTED 2026-10-03. This
        // reader's own real-byte check found all 45 elements resolve to
        // clean strings exactly matching spec §5.1's documented
        // vocabulary, settling the spec's own open "40 vs 45" question in
        // favour of 45. ---
        CHECK(cat.wheelNames().size() == 45);
        if (cat.wheelNames().size() == 45) {
            CHECK(cat.wheelNames().front() == "W_000_F_Extra_High_Profile");
            CHECK(cat.wheelNames().back() == "W_006_R_Extra_Low_Profile");
        }
        CHECK(cat.region2Names().size() == cat.wheelNames().size());  // back-compat alias

        // --- The "Family00N" array (+0x28/+0x2C): spec §5.1's own
        // HYPOTHESIS for this array's purpose, confirmed empirically here. ---
        CHECK(cat.familyNames().size() == 7);
        if (cat.familyNames().size() == 7) {
            CHECK(cat.familyNames()[0] == "Family001");
            CHECK(cat.familyNames()[6] == "Family007");
        }
    }

    // --- Negative cases: hand-rolled small buffers, not the real file. ---
    {
        // Too short for even the 48-byte header.
        std::vector<uint8_t> tiny(16, 0);
        CvtfCatalog cat;
        std::string why;
        CHECK(!CvtfCatalog::tryParse(vpp::ByteView(tiny.data(), tiny.size()), cat, why));
    }
    {
        // Real header's first 48 bytes, with the magic's first byte flipped.
        std::vector<uint8_t> corrupted(kRealCvtfBytes, kRealCvtfBytes + 48);
        corrupted[0] ^= 0xFF;
        CvtfCatalog cat;
        std::string why;
        CHECK(!CvtfCatalog::tryParse(vpp::ByteView(corrupted.data(), corrupted.size()), cat, why));
    }
    {
        // Real header's first 48 bytes, but with the Region-1 offset field
        // (+0x0C) forced to the sentinel - must be rejected, not silently
        // treated as offset 0.
        std::vector<uint8_t> buf(kRealCvtfBytes, kRealCvtfBytes + 48);
        buf[0x0C] = 0xFF; buf[0x0D] = 0xFF; buf[0x0E] = 0xFF; buf[0x0F] = 0xFF;
        CvtfCatalog cat;
        std::string why;
        CHECK(!CvtfCatalog::tryParse(vpp::ByteView(buf.data(), buf.size()), cat, why));
    }

    if (g_failures == 0) {
        std::cout << "All synthetic cvtf tests passed.\n";
        return 0;
    }
    std::cout << g_failures << " check(s) FAILED.\n";
    return 1;
}
